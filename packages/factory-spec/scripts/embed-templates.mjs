// Embeds templates/code-review-team/ into src/team/codeReviewTeam.generated.ts, so the package
// ships the template as data and stays free of I/O. Run after changing a template file:
//
//   pnpm --filter @consola/factory-spec templates:embed
//
// `src/team/codeReviewTeam.test.ts` fails while the generated module and the files differ.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const packageDir = join(import.meta.dirname, '..');
const templateDir = join(packageDir, 'templates', 'code-review-team');
const target = join(packageDir, 'src', 'team', 'codeReviewTeam.generated.ts');

/** Every file under `dir`, as paths relative to `root` with `/`, in byte order. */
function filesUnder(dir, root = dir) {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) return filesUnder(path, root);
      if (entry.name.startsWith('.')) return [];
      return [relative(root, path).split(sep).join('/')];
    })
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

const entries = filesUnder(templateDir).map(
  (path) =>
    `  {\n    path: ${JSON.stringify(path)},\n    content: ${JSON.stringify(readFileSync(join(templateDir, path), 'utf8'))},\n  },\n`,
);

const module = `// Generated by scripts/embed-templates.mjs from templates/code-review-team/. Do not edit:
// change the files there and run \`pnpm --filter @consola/factory-spec templates:embed\`.
import type { TeamFile } from './types';

/** The code-review team: an orchestrator that dispatches a review agent and posts its findings. */
export const CODE_REVIEW_TEAM_FILES: readonly TeamFile[] = [
${entries.join('')}];
`;

writeFileSync(target, module);
console.log(`Wrote ${relative(packageDir, target)} (${entries.length} files).`);
